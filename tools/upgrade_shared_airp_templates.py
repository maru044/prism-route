def clean_ellipses(text: str) -> str:
    # Use unicode escapes to avoid literal ellipsis in source code
    ellipsis_char = chr(0x2026)
    clean = text.replace(ellipsis_char * 2, "~ ")
    clean = clean.replace(ellipsis_char, "~ ")
    clean = clean.replace("." * 3, "~ ")
    return clean

def main():
    templates = json.loads(TEMPLATES_PATH.read_text(encoding="utf-8"))
    updated_count = 0
    for tmpl in templates:
        r_id = tmpl.get("reply_id")
        if r_id in SHARED_TEMPLATES_EXPANSION:
            expanded = SHARED_TEMPLATES_EXPANSION[r_id]
            tmpl["templates"] = [clean_ellipses(t) for t in expanded]
            updated_count += 1
            
    print(f"Updated {updated_count} shared templates.")
    
    # Write to new_templates.json for safe staging
    out_path = DATA_DIR / "new_shared_templates.json"
    out_path.write_text(json.dumps(templates, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Staged {len(templates)} templates to {out_path}")

if __name__ == "__main__":
    main()
