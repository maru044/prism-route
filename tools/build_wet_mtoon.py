"""Generate a project-owned MToon variant with narrowly scoped wetness hooks.

The upstream MIT plugin is never edited. Exact anchors fail on upstream drift.
"""
import hashlib
import argparse
from pathlib import Path


def build(check=False):
    root = Path(__file__).resolve().parents[1]
    source = root / "addons/mtoon/mtoon_common.gdshaderinc"
    original = source.read_text(encoding="utf-8")
    code = original
    hooks = {
        "void vertex() {": "void vertex() {\n\twet_world_y = (MODEL_MATRIX * vec4(VERTEX, 1.0)).y;",
        "\tlit *= _Color;": "\tlit *= _Color;\n\twet_amount = wet_sample(wet_world_y - wet_root_height);\n\tfloat wet_diffuse = 1.0 - wet_darkening * wet_amount;\n\tlit.rgb *= wet_diffuse;\n\tshade.rgb *= wet_diffuse;",
        "\tEMISSION = emission;": "\tEMISSION = emission * (1.0 - wet_darkening * wet_amount);",
        "\tDIFFUSE_LIGHT += diffuse_output / fragment_albedo_output;": "\tDIFFUSE_LIGHT += diffuse_output / fragment_albedo_output;\n\t// Thin water-film glint only in air; attenuation keeps shadows dark.\n\tfloat air = wet_contact ? smoothstep(0.0, 0.04, wet_world_y - wet_water_level) : 1.0;\n\tvec3 wet_n = normalize(viewNormal);\n\tvec3 wet_h = normalize(LIGHT + VIEW + vec3(0.000001));\n\tfloat wet_fresnel = 0.04 + 0.96 * pow(1.0 - clamp(dot(wet_n, VIEW), 0.0, 1.0), 5.0);\n\tfloat wet_specular = pow(max(dot(wet_n, wet_h), 0.0), wet_gloss_power);\n\tSPECULAR_LIGHT += LIGHT_COLOR * ATTENUATION * max(dot(wet_n, LIGHT), 0.0) * wet_specular * (0.25 + 0.75 * wet_fresnel) * wet_gloss * wet_amount * air;",
    }
    for anchor, replacement in hooks.items():
        if code.count(anchor) != 1:
            raise ValueError(f"Upstream MToon hook changed: {anchor!r}")
        code = code.replace(anchor, replacement)
    uniforms = """
// Project-owned wetness extension. Height samples follow the actor root.
// This is a coarse body-height history, not a UV-painted wetness simulation.
uniform float wet_levels[24];
uniform float wet_root_height = 0.0;
uniform float wet_water_level = -10000.0;
uniform bool wet_contact = false;
uniform float wet_darkening = 0.0;
uniform float wet_gloss = 0.0;
uniform float wet_gloss_power = 64.0;
varying float wet_world_y;
varying float wet_amount;

float wet_sample(float height) {
    float sample_index = clamp((height + 0.15) / 2.30 * 23.0, 0.0, 23.0);
    int low = int(floor(sample_index));
    int high = min(low + 1, 23);
    return clamp(mix(wet_levels[low], wet_levels[high], fract(sample_index)), 0.0, 1.0);
}

"""
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    license_text = (root / "addons/mtoon/LICENSE").read_text(encoding="utf-8")
    header = "// Generated by tools/build_wet_mtoon.py; upstream SHA256: " + digest + "\n"
    header += "/*\nDerived from addons/mtoon/mtoon_common.gdshaderinc\n" + license_text + "\n*/\n"
    out = root / "shaders/characters/wet_mtoon_common.gdshaderinc"
    generated = header + uniforms + code
    if check:
        if not out.exists() or out.read_text(encoding="utf-8") != generated:
            raise ValueError("Generated wet MToon is stale; run tools/build_wet_mtoon.py")
    else:
        out.write_text(generated, encoding="utf-8")
    print("WET_MTOON_CHECKED" if check else "WET_MTOON_BUILT", digest)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
